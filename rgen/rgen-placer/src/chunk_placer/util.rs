//! Helpers shared by the ground feature chunk placers.
//!
//! Chunk placers are handed an `Rng` that only depends on the world seed (and
//! the placer's index within its biome), so it is the same for every chunk.
//! Placers that want different results in each chunk need to mix in the chunk
//! position, which is what these helpers do.

use rgen_base::{ChunkPos, ChunkRelPos};

use crate::{Random, Rng};

/// Hashes a seed together with a pair of coordinates.
pub(crate) fn mix(seed: u64, x: i32, z: i32) -> u64 {
  let mut rng = Rng::new(seed ^ ((x as u32 as u64) << 32) ^ (z as u32 as u64));
  rng.next();
  rng.next()
}

/// Builds an `Rng` that is unique to this chunk.
pub(crate) fn chunk_rng(rng: &mut Rng, chunk_pos: ChunkPos) -> Rng {
  Rng::new(mix(rng.next(), chunk_pos.x(), chunk_pos.z()))
}

/// Picks a whole number of attempts, which averages out to `avg`.
pub(crate) fn count(rng: &mut Rng, avg: f64) -> u32 {
  let whole = avg.floor();
  let extra = rng.range(0.0..1.0) < avg - whole;
  whole as u32 + extra as u32
}

/// A round feature, centered on some block column. The center might be in a
/// neighboring chunk.
pub(crate) struct Blob {
  pub x:    i32,
  pub z:    i32,
  /// A seed unique to this blob, which is the same no matter which chunk is
  /// asking about it.
  pub seed: u64,
}

impl Blob {
  /// A random number generator for a single column of this blob. This gives the
  /// same results in every chunk the blob touches.
  pub fn column_rng(&self, x: i32, z: i32) -> Rng { Rng::new(mix(self.seed, x, z)) }
}

/// Returns every blob that might touch `chunk_pos`, assuming blobs have a
/// radius of at most 16.
///
/// `base` must be the same for every chunk. Blobs are generated by the
/// chunk they are centered in, so a blob that crosses a chunk border is seen
/// (identically) by both chunks, and no seam shows up.
pub(crate) fn blobs_near(base: u64, chunk_pos: ChunkPos, avg: f64) -> Vec<Blob> {
  let mut out = vec![];

  for dx in -1..=1 {
    for dz in -1..=1 {
      let chunk = ChunkPos::new(chunk_pos.x() + dx, chunk_pos.z() + dz);
      let mut rng = Rng::new(mix(base, chunk.x(), chunk.z()));
      let min = chunk.min_block_pos();

      for _ in 0..count(&mut rng, avg) {
        let x = min.x + rng.range(0..16);
        let z = min.z + rng.range(0..16);
        out.push(Blob { x, z, seed: rng.next() });
      }
    }
  }

  out
}

/// Calls `f` for every point of every clump that lands on a column of this
/// chunk.
///
/// A clump is a set of `attempts` random walks of `radius` steps, which all
/// start at the clump's center. Like `blobs_near`, clumps are generated by
/// their home chunk, so a clump that crosses a chunk border is continuous.
/// `f` is given the column (at y=0), and a seed unique to that point.
pub(crate) fn for_each_clump_point(
  base: u64,
  chunk_pos: ChunkPos,
  avg: f64,
  radius: &std::ops::RangeInclusive<u8>,
  attempts: u32,
  mut f: impl FnMut(ChunkRelPos, u64),
) {
  let min = chunk_pos.min_block_pos();

  for blob in blobs_near(base, chunk_pos, avg) {
    let mut rng = Rng::new(blob.seed);
    let radius = rng.range::<i32>((*radius.start()).into()..=(*radius.end()).into());

    for _ in 0..attempts {
      let mut x = blob.x;
      let mut z = blob.z;
      for _ in 0..radius {
        x += rng.range(-1..=1);
        z += rng.range(-1..=1);
      }

      // This is always drawn, so every chunk agrees on what the next point is.
      let seed = rng.next();

      let (rel_x, rel_z) = (x - min.x, z - min.z);
      if (0..16).contains(&rel_x) && (0..16).contains(&rel_z) {
        f(ChunkRelPos::new(rel_x as u8, 0, rel_z as u8), seed);
      }
    }
  }
}
